static uint32_t preset_logical_limit(uint32_t e)
{
    if (e == 0u) return 48u;
    if (e == 1u) return 49u;
    if (e == ENGI_PROPHET) return P5_FACTORY_N;
    switch (e) {
    case 2u: return 37u;  /* PHASE: five restored originals at IDs 32..36 */
    case 3u: return 38u;  /* LOFI */
    case 5u: return 38u;  /* FORMANT */
    case 6u: return 44u;  /* TRIO */
    case 7u: return 40u;  /* DRAWBAR */
    case ENGI_FM6: return 53u; /* five retained local FM6 sounds + 17 original FM-1 voices */
    case ENGI_NOISE: return 13u;  /* MORPH: thirteen compact wavetable presets */
    default: return 32u;
    }
}
static const preset_t *preset_data(uint32_t e, uint32_t logical)
{
    uint32_t k;
    if (e >= NENGINES || logical >= 128u) return 0;
    if (e == 0u && logical >= 44u && logical < 46u)
        return &ENGINES[e]->presets[logical - 22u];
    if (e == 0u && logical >= 46u && logical < 48u)
        return &ENGINES[e]->presets[logical - 22u];
    if (e == 1u && logical == 48u)
        return &ENGINES[e]->presets[23];
    if (e == 6u && logical >= 40u && logical < 44u)
        return &ENGINES[e]->presets[logical - 30u];
    if (e == 7u && logical == 39u)
        return &ENGINES[e]->presets[2];
    if (e == ENGI_FM6 && logical >= 36u && logical < 53u)
        return &ENGINES[e]->presets[logical - 31u];
    if (e == ENGI_NOISE && logical < 13u)
        return &ENGINES[e]->presets[logical];
    /* Preserve saved-project IDs after GLACIER (5) and STILL ORBIT (7) were removed. */
    if (e == ENGI_DRONE) {
        if (logical == 5u || logical == 7u) return 0;
        if (logical == 6u) return &ENGINES[e]->presets[5];
        if (logical == 8u) return &ENGINES[e]->presets[6];
        if (logical == 9u) return &ENGINES[e]->presets[7];
    }
    k = PRESET_MAP[e][logical];
    return k == 255u || k >= PRESET_COMPACT_N[e] ? 0 : &ENGINES[e]->presets[k];
}
static uint32_t preset_compact_count(uint32_t e)
{
    return e < NENGINES ? PRESET_COMPACT_N[e] : 0u;
}
static const preset_t *preset_compact_data(uint32_t e, uint32_t k)
{
    return e < NENGINES && k < PRESET_COMPACT_N[e] ? &ENGINES[e]->presets[k] : 0;
}

